<div class="text-gray-800 min-w-full">
    <p class="mb-2">Follow these simple steps to make a small icon (favicon) for your website.</p>
    <ol class="list-decimal list-inside space-y-2">
        <li>
            <span class="font-semibold">Prepare your logo</span><br>
            Save your logo (or a simple picture) as a <span class="font-semibold">PNG file</span>. Make sure it looks clear in a small square.
            <!-- Screenshot placeholder -->
        </li>
        <li>
            <span class="font-semibold">Go to the favicon generator</span><br>
            Open this website:
            <a href="https://favicon.io/" target="_blank" rel="noopener" class="text-blue-600 underline hover:text-blue-800">https://favicon.io/</a>
            <!-- Screenshot placeholder -->
        </li>
        <li>
            <span class="font-semibold">Upload your logo</span><br>
            Click <em>“Select the PNG -> ICO”</em>, then upload your PNG file.
            <!-- Screenshot placeholder -->
        </li>
        <li>
            <span class="font-semibold">Download the result</span><br>
            Click <em>Download</em> to get a ZIP file and save it on your computer.
            <!-- Screenshot placeholder -->
        </li>
        <li>
            <span class="font-semibold">Open the ZIP</span><br>
            Extract (open) the ZIP file. Look for a file that ends with
            <code class="bg-gray-100 px-1 rounded text-sm">.ico</code>
            (for example:
            <code class="bg-gray-100 px-1 rounded text-sm">favicon.ico</code>).
            <!-- Screenshot placeholder -->
        </li>
        <li>
            <span class="font-semibold">Use the <code class="bg-gray-100 px-1 rounded text-sm">favicon.ico</code> file</span><br>
            This is the icon you’ll upload to the website or give to your web developer. You’re done! 🎉
        </li>
    </ol>

    <div class="bg-gray-50 border border-gray-200 rounded-lg p-4 mt-6">
        <p class="font-semibold mb-2">Tips:</p>
        <ul class="list-disc list-inside space-y-1 text-gray-700">
            <li>Simple shapes and high contrast look best at small sizes.</li>
            <li>If your logo is not square, crop it to a square before uploading.</li>
        </ul>
    </div>
</div>
